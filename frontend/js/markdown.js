/**
 * ================================================================
 * 轻量级 Markdown 渲染器 — markdown.js
 * ================================================================
 * 将 AI 回复中的 Markdown 语法转为 HTML，支持：
 * - 代码块（```语言\n代码\n```）
 * - 行内代码（`code`）
 * - 粗体（**文本**）
 * - 标题（### 标题）
 * - 无序列表（- 或 * 开头）
 * - 换行/分段
 * - 安全转义（防止 XSS）
 */

/**
 * 将 Markdown 文本转为安全的 HTML
 * @param {string} text — Markdown 原始文本
 * @returns {string} — 安全 HTML 字符串
 */
function renderMarkdown(text) {
    if (!text) return "";

    // ================================================================
    // 第 1 步：HTML 转义，防止 XSS 攻击
    // ================================================================
    let html = text
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;");

    // ================================================================
    // 第 2 步：代码块（```语言\n代码\n```）
    // 必须在其他规则之前处理，因为代码块内不解析 markdown
    // ================================================================
    html = html.replace(/```(\w*)\n?([\s\S]*?)```/g, function (match, lang, code) {
        // 去掉代码首尾多余的空行
        code = code.replace(/^\n+|\n+$/g, "");
        var langClass = lang ? ' class="language-' + lang + '"' : "";
        return (
            '<pre><code' + langClass + ">" +
            code +
            "</code></pre>"
        );
    });

    // ================================================================
    // 第 3 步：行内代码（`code`）
    // ================================================================
    html = html.replace(/`([^`]+)`/g, "<code>$1</code>");

    // ================================================================
    // 第 4 步：粗体（**文本**）
    // ================================================================
    html = html.replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");

    // ================================================================
    // 第 5 步：标题（### 标题，支持 1-3 级）
    // ================================================================
    html = html.replace(/^### (.+)$/gm, "<h3>$1</h3>");
    html = html.replace(/^## (.+)$/gm, "<h2>$1</h2>");
    html = html.replace(/^# (.+)$/gm, "<h1>$1</h1>");

    // ================================================================
    // 第 6 步：无序列表（- 或 * 开头）
    // ================================================================
    html = html.replace(/^[\-\*] (.+)$/gm, "<li>$1</li>");
    // 将连续的 <li> 包裹在 <ul> 中
    html = html.replace(/(<li>.*?<\/li>(\n?<li>.*?<\/li>)*)/g, "<ul>$1</ul>");

    // ================================================================
    // 第 7 步：分段（连续两个换行 → 新段落）
    // ================================================================
    var paragraphs = html.split(/\n\n+/);
    html = paragraphs
        .map(function (p) {
            p = p.trim();
            if (!p) return "";
            // 如果已经是一个块级元素（pre/ul/h1/h2/h3），不包裹 <p>
            if (
                p.startsWith("<pre>") ||
                p.startsWith("<ul>") ||
                p.startsWith("<h1>") ||
                p.startsWith("<h2>") ||
                p.startsWith("<h3>")
            ) {
                return p;
            }
            return "<p>" + p + "</p>";
        })
        .join("");

    // ================================================================
    // 第 8 步：单个换行 → <br>
    // ================================================================
    html = html.replace(/\n/g, "<br>");

    return html;
}
