"""
================================================================
System Prompt 构建器 — system_prompt.py
================================================================
根据当前上下文（检索到的记忆）动态构建 system prompt。

核心功能：
- 基础人设：小智的标准设定
- 时间注入：告知模型当前日期和时间，解决"今天几号"类问题
- 记忆注入：如果检索到相关记忆，追加到 system prompt 中
- 格式提示：引导 LLM 的风格和输出格式
"""

from datetime import datetime, timezone, timedelta

# ================================================================
# 北京时间（UTC+8）
# ================================================================
# 为什么不用 datetime.now()：
#   直接调用会跟随"运行代码那台机器"的时区设置。云服务器默认时区
#   常常是 UTC，会导致慢 8 小时。这里显式指定偏移量，无论代码跑在
#   Windows 本地还是 Linux 服务器上，结果都一致。
#   另外没使用 zoneinfo（Asia/Shanghai），是为了避免 Windows 本地
#   缺少 tzdata 时报 ZoneInfoNotFoundError。
BEIJING_TZ = timezone(timedelta(hours=8))

_WEEKDAYS = ["星期一", "星期二", "星期三", "星期四", "星期五", "星期六", "星期日"]


def current_time_notice() -> str:
    """
    生成"当前时间"提示文本。

    注意：本函数每次调用都会重新读取系统时钟。调用方必须保证在
    **每次请求**时都重新调用，不要在模块加载时缓存结果，否则模型
    会一直以为停留在服务启动的那一刻。

    返回：
        形如「当前时间是 2026年09月15日 22:37（星期二）。...」
    """
    now = datetime.now(BEIJING_TZ)
    return (
        f"当前时间是 {now.strftime('%Y年%m月%d日 %H:%M')}"
        f"（{_WEEKDAYS[now.weekday()]}）。"
        "当用户询问日期、时间、星期几，或涉及「今天」「昨天」「明天」"
        "「现在」这类相对时间时，必须以上述时间为准回答，"
        "不要凭记忆推测或编造。"
    )


def build_system_prompt(memories: list[str] | None = None) -> str:
    """
    构建完整的 system prompt

    参数：
        memories: 相关记忆文本列表（可选），如 ["用户叫张三", "用户喜欢打篮球"]

    返回：
        完整的 system prompt 字符串
    """
    # ================================================================
    # 基础人设
    # ================================================================
    base = (
        "你是小智，一个友好的中文 AI 助手。"
        "你运行在用户本地电脑上，后端通过阿里云百炼平台调用 Qwen 大模型来生成回复。"
        "你的回答应该简洁、准确、易于理解。"
        "请始终使用中文回复，除非用户明确要求使用其他语言。"
        "如果你不知道答案，请诚实地告诉用户，不要编造信息。"
    )

    # ================================================================
    # 时间注入
    # ================================================================
    # 大模型本身没有时钟，知识只截止到训练数据的时间点。
    # 不告知当前时间的话，问"今天几号"它会凭空编造一个答案。
    time_section = f"\n\n## 当前时间\n{current_time_notice()}"

    # ================================================================
    # 工具使用说明
    # ================================================================
    # 两个工具是分工关系：run_python 负责「算」，plot_chart 负责「画」。
    # 不写清楚的话，模型容易用 run_python 跑 matplotlib 出图片——
    # 慢、不可交互、还占服务器 CPU。
    tools_section = (
        "\n\n## 工具使用\n"
        "你有两个工具，注意分工：\n"
        "- **run_python**：在服务器上执行 Python 代码，用于计算、读取数据文件、数据处理。\n"
        "- **plot_chart**：把数据渲染成用户界面里的**可交互图表**（悬停看数值、可导出 PNG）。\n"
        "**规则（必须遵守）：**\n"
        "1. **禁止用 matplotlib / seaborn 给用户展示图表**（服务端绘图已关闭，代码里 import 它们会直接报错）"
        "——只要是要「看」图表（画个柱状图、可视化一下、看下趋势、对比一下），一律用 **plot_chart**。\n"
        "2. 用户要是问「图片在哪 / 能不能下载 / 我要放进报告」，告诉他点击图表右上角的「⬇ 导出 PNG」即可，"
        "不要试图用 Python 画图。\n"
        "3. 数据在用户上传的文件里时：先用 run_python 读取文件并 print 出 JSON 数据，"
        "再把数据交给 plot_chart 画图（路径必须用 f'{UPLOAD_DIR}/文件名.csv' 拼接）。\n"
        "3.1 **一次上传多个文件时**（文件名带相同批次前缀，如 `a1b2c3d4_1_一月.csv`、`a1b2c3d4_2_二月.csv`）：\n"
        "  - 它们多半是**同一份数据切开的分片**，先合并再分析：\n"
        "    `paths = sorted(glob.glob(f'{UPLOAD_DIR}/a1b2c3d4_*.csv')); df = pd.concat([pd.read_csv(p) for p in paths], ignore_index=True)`\n"
        "  - 合并后**务必打印总行数**，让用户知道数据量对不对。\n"
        "  - 若各文件**列不一样**（不是分片而是不同维度/不同表），不要硬拼，"
        "改用 `pd.merge(..., on='共同列')` 关联，或分别分析。\n"
        "  - 合并的数据量可能很大，先 `print(df.shape)` 和 `df.head()` 自检，再决定是否聚合。\n"
        "3.2 **CSV 编码已自动探测**：`pd.read_csv(path)` 不传 `encoding` 也能正确读出中文"
        "（UTF-8 / GBK / 带 BOM 均已支持）。"
        "**不要**再写「先试 gbk，失败再试 utf-8」的循环试探 —— 那是在浪费工具调用轮数。\n"
        "4. **说「已为您生成图表」之前，必须真的调用过 plot_chart**——绝对不许只回复文字假装生成"
        "（那样用户界面是空白的，属于严重错误）。\n"
        "5. **图表里的数值必须来自用户提供的数字或工具执行结果，绝对不要凭记忆编造数据。**"
    )

    prompt = base + time_section + tools_section

    # ================================================================
    # 记忆注入
    # ================================================================
    if memories and len(memories) > 0:
        memory_lines = "\n".join([f"- {m}" for m in memories])
        memory_section = (
            f"\n\n## 关于用户的已知信息（跨会话持久记忆）\n"
            f"以下是你从之前的对话中记住的关于用户的**事实**，"
            f"它们来自数据库中的记忆系统：\n"
            f"{memory_lines}\n"
            f"**重要：当用户的问题与这些信息相关时，你必须自然地引用它们。"
            f"这些是你已经知道的事实，不需要用户再次告诉你。**"
        )
        prompt += memory_section

    return prompt
